import fs from 'node:fs';
import path from 'node:path';
import { ROOT, read, source, write } from './sources.mjs';

export async function buildUnicode() {
  const blocksTxt = read(await source('blocks'));
  const version = /^# Blocks-(\d+)\.(\d+)\.\d+\.txt/m.exec(blocksTxt);
  if (!version) throw new Error('Blocks.txt has no version header');
  const major = version[1];
  const rows = [];
  const ranges = [];
  let first = null;
  for (const line of read(await source('unicodeData')).split('\n')) {
    if (!line) continue;
    const f = line.split(';');
    const cp = parseInt(f[0], 16);
    let name = f[1];
    const gc = f[2];
    if (name.endsWith(', First>')) {
      first = [cp, name.slice(1, -8), gc];
      continue;
    }
    if (name.endsWith(', Last>')) {
      ranges.push([first[0], cp, first[1], first[2]]);
      continue;
    }
    if (name === '<control>') name = f[10] || 'CONTROL';
    rows.push([cp, name, gc]);
  }
  // Compact form: hex gap from the previous code point (empty for +1),
  // lower-case name, and the category only when it changes.
  let prev = -1;
  let prevGc = null;
  const lines = rows.map(([cp, n, g]) => {
    const gap = cp - prev;
    prev = cp;
    const line = `${gap === 1 ? '' : gap.toString(16)}|${n.toLowerCase()}${g !== prevGc ? `|${g}` : ''}`;
    prevGc = g;
    return line;
  });
  const out = path.join(ROOT, `public/data/unicode-names-${major}.txt`);
  fs.writeFileSync(out, lines.join('\n') + '\n');
  console.log(`wrote public/data/unicode-names-${major}.txt`);
  const blocks = [
    ...blocksTxt.matchAll(/^([0-9A-F]+)\.\.([0-9A-F]+); (.+)$/gm),
  ].map((m) => [parseInt(m[1], 16), parseInt(m[2], 16), m[3].trim()]);
  write(
    'unicode-blocks.ts',
    `// Unicode ${version[1]}.${version[2]} blocks (Blocks.txt) and the code-point ranges whose names are
// derived rather than listed (UnicodeData.txt). © Unicode, Inc., Unicode License v3.
// Per-character names live in public/data/unicode-names-${major}.txt, fetched on demand.
// Generated by scripts/reference-data (npm run data:reference).

export const UNICODE_VERSION = '${version[1]}.${version[2]}';

/** [first, last, name] */
export const BLOCKS: [number, number, string][] = ${JSON.stringify(blocks)};

/** [first, last, label, general category] */
export const NAMED_RANGES: [number, number, string, string][] = ${JSON.stringify(ranges)};
`,
  );
  return major;
}
