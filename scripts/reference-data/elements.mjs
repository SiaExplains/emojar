// lib/online-tools/data/elements.ts from the PubChem periodic table (public
// domain) plus the hand-checked tables in elements-tables.mjs.
import {
  DISCOVERER,
  MASS_NUMBER,
  STANDARD_WEIGHT,
  YEAR_FIX,
} from './elements-tables.mjs';
import { read, source, write } from './sources.mjs';

function parseCsv(text) {
  const rows = [];
  for (const line of text.trim().split('\n')) {
    const cells = [];
    let cur = '';
    let q = false;
    for (const ch of line) {
      if (ch === '"') q = !q;
      else if (ch === ',' && !q) {
        cells.push(cur);
        cur = '';
      } else cur += ch;
    }
    cells.push(cur.replace(/\r$/, ''));
    rows.push(cells);
  }
  const [head, ...body] = rows;
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h, r[i]])));
}

/** Period and group (null for the lanthanide/actinide rows). */
function position(z) {
  const periods = [
    [1, 2],
    [3, 10],
    [11, 18],
    [19, 36],
    [37, 54],
    [55, 86],
    [87, 118],
  ];
  const p = periods.findIndex(([a, b]) => z >= a && z <= b) + 1;
  const off = z - periods[p - 1][0];
  if (p === 1) return [p, z === 1 ? 1 : 18];
  if (p <= 3) return [p, off < 2 ? off + 1 : off + 11];
  if (p <= 5) return [p, off + 1];
  if (off < 2) return [p, off + 1];
  if (off < 17) return [p, null];
  return [p, off - 13];
}

const num = (v) =>
  v === '' || v == null || isNaN(Number(v)) ? null : Number(v);

export async function buildElements() {
  const rows = parseCsv(read(await source('pubchem')));
  const out = rows.map((r) => {
    const z = Number(r.AtomicNumber);
    const s = r.Symbol;
    const [p, g] = position(z);
    const b = g === null ? 'f' : g <= 2 || z === 2 ? 's' : g <= 12 ? 'd' : 'p';
    const std = STANDARD_WEIGHT[s];
    return {
      z,
      s,
      n: r.Name,
      m: std ?? Number(r.AtomicMass),
      ...(MASS_NUMBER[s] ? { mn: MASS_NUMBER[s] } : {}),
      p,
      g,
      b,
      c: r.GroupBlock,
      e: r.ElectronConfiguration.replace(/ \((calculated|predicted)\)/, ''),
      ep: /predicted|calculated/.test(r.ElectronConfiguration),
      en: num(r.Electronegativity),
      mp: num(r.MeltingPoint),
      bp: num(r.BoilingPoint),
      d: num(r.Density),
      st: r.StandardState.replace('Expected to be a ', '').toLowerCase(),
      se: r.StandardState.includes('Expected'),
      y: YEAR_FIX[s] ?? r.YearDiscovered,
      by: DISCOVERER[s],
      ox: r.OxidationStates.replace(/\s/g, '')
        .split(',')
        .filter(Boolean)
        .map(Number),
    };
  });
  if (out.length !== 118)
    throw new Error(`expected 118 elements, got ${out.length}`);
  for (const e of out) {
    if (!e.by) throw new Error(`no discoverer for ${e.s}`);
    if ((e.mn === undefined) !== e.s in STANDARD_WEIGHT)
      throw new Error(`weight/mass-number mismatch for ${e.s}`);
  }
  write(
    'elements.ts',
    `// Generated by scripts/reference-data (npm run data:reference) from the
// PubChem periodic table (public domain, US government) with IUPAC/CIAAW
// standard atomic weights and hand-checked discoverers. Temperatures in
// kelvin, density in g/cm³. mn: mass number of the longest-lived isotope
// when there is no standard atomic weight.

export type ElementData = {
  z: number;
  s: string;
  n: string;
  m: number;
  mn?: number;
  p: number;
  g: number | null;
  b: 's' | 'p' | 'd' | 'f';
  c: string;
  e: string;
  ep: boolean;
  en: number | null;
  mp: number | null;
  bp: number | null;
  d: number | null;
  st: string;
  se: boolean;
  y: string;
  by: string;
  /** Common oxidation states (PubChem). */
  ox: number[];
};

export const ELEMENTS: ElementData[] = ${JSON.stringify(out)};
`,
  );
}
